//! Pure mapping layer for de-identified exports from the Surgical Registry.
//! No database, network, or credential dependency is allowed in this crate.
use serde::{Deserialize, Serialize};
use serde_json::Value;
use uuid::Uuid;

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct RegistryExport {
    pub format: String, pub version: u32, pub exported_at: String,
    pub source: RegistrySource, pub cases: Vec<RegistryCase>,
}
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct RegistrySource { pub system: String, pub schema_family: String, pub registry_version: Option<String> }
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct RegistryCase {
    /// Keyed pseudonym generated by the trusted exporter; never a registry UUID or study ID.
    pub source_case_ref: String,
    pub procedure_module: String, pub procedure_label: Option<String>, pub surgery_date: Option<String>,
    pub status: String, pub values: Vec<RegistryFieldValue>, pub learning_answer: Option<String>,
    pub learning_sealed_at: Option<String>, pub learnings: Vec<RegistryLearning>, pub tags: Vec<String>,
}
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct RegistryFieldValue {
    pub field: String, pub value: Value, pub source: Option<String>,
    pub evidence: Option<String>, pub changed_at: Option<String>,
}
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct RegistryLearning {
    pub ordinal: u8, pub shown_by: String, pub sign_tags: Vec<String>, pub how_showed: Option<String>,
    pub items: Vec<RegistryLearningItem>, pub amendments: Vec<RegistryAmendment>, pub added_after_seal: bool,
}
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct RegistryLearningItem { pub slot: String, pub text: String, pub origin: String }
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct RegistryAmendment { pub slot: String, pub text: String, pub created_at: String }

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum FieldOrigin { Said, Default, Derived, Chip, HistopathPhoto, Manual }
impl FieldOrigin {
    pub fn parse(raw: Option<&str>) -> Self {
        match raw {
            Some("said") => Self::Said, Some("default") => Self::Default, Some("derived") => Self::Derived,
            Some("histopath_photo") => Self::HistopathPhoto, Some("manual") => Self::Manual,
            Some("chip") | None | Some(_) => Self::Chip,
        }
    }
    pub fn epistemic(&self) -> &'static str {
        match self { Self::Said | Self::Chip | Self::HistopathPhoto | Self::Manual => "reported", Self::Default | Self::Derived => "inferred" }
    }
    pub fn is_candidate_for_learning(&self) -> bool {
        matches!(self, Self::Said | Self::Chip | Self::HistopathPhoto | Self::Manual)
    }
}

/// Stable keyed pseudonym helper. This is pseudonymization, not anonymization; keep salt only at the trusted boundary.
pub fn pseudonymous_ref(source_ref: &str, salt: &[u8]) -> String {
    use sha2::{Digest, Sha256};
    let mut h = Sha256::new(); h.update(salt); h.update([0]); h.update(source_ref.as_bytes());
    format!("sr-{}", hex::encode(&h.finalize()[..16]))
}

fn node(id: Uuid, kind: &str, scope: &str, label: String, epistemic: &str, note: String, retention: &str, data: Value) -> Value {
    serde_json::json!({
        "id":id,"node_type":kind,"knowledge_scope":scope,"label":label,"epistemic_status":epistemic,
        "confidence":null,"lifecycle_status":"active","retention":retention,
        "provenance":{"source_type":"surgical_registry","source_id":null,"source_version":null,"note":note},
        "temporal":{"observed_at":chrono::Utc::now().to_rfc3339(),"valid_from":null,"valid_until":null},
        "review":{"state":"not_required","reviewer_ref":null,"reviewed_at":null,"rationale":null},
        "data":data,"tags":[]
    })
}
fn edge(from: Uuid, relation: &str, to: Uuid, note: &str) -> Value {
    serde_json::json!({
        "id":Uuid::new_v4(),"from":from,"relation":relation,"to":to,"epistemic_status":"reported",
        "lifecycle_status":"active","provenance":{"source_type":"surgical_registry","source_id":null,"source_version":null,"note":note},
        "observed_at":chrono::Utc::now().to_rfc3339(),"confidence":null,"note":null
    })
}
fn compact(v: &Value) -> String {
    match v { Value::String(s)=>s.clone(), Value::Null=>"not recorded".into(), _=>v.to_string() }
}

/// Map one saved, sealed registry case. No summary generation or semantic interpretation occurs here.
pub fn map_registry_case(c: &RegistryCase) -> Result<(Vec<Value>,Vec<Value>),String> {
    if c.source_case_ref.trim().is_empty() { return Err("source_case_ref must be a non-empty pseudonymous reference".into()); }
    if !matches!(c.status.as_str(),"captured"|"pending_review"|"complete") { return Err("only saved cases may be exported".into()); }
    if c.learning_sealed_at.is_none() { return Err("case learning must be sealed before knowledge export".into()); }
    let case_id=Uuid::new_v4();
    let mut nodes=vec![node(case_id,"case_episode","case_specific",
        format!("{} — {}",c.procedure_label.as_deref().unwrap_or(&c.procedure_module),c.surgery_date.as_deref().unwrap_or("date not recorded")),
        "reported",format!("Pseudonymous source ref {}; registry status {}",c.source_case_ref,c.status),"episodic",
        serde_json::json!({"procedure_module":c.procedure_module,"procedure_label":c.procedure_label,"surgery_date":c.surgery_date}))];
    let mut edges=Vec::new();
    for f in &c.values {
        let origin=FieldOrigin::parse(f.source.as_deref());
        if !origin.is_candidate_for_learning() { continue; }
        let id=Uuid::new_v4();
        nodes.push(node(id,"observation","case_specific",format!("{}: {}",f.field,compact(&f.value)),origin.epistemic(),
            format!("case_values field={} source={}",f.field,f.source.as_deref().unwrap_or("chip")),"episodic",
            serde_json::json!({"field":f.field,"value":f.value,"evidence":f.evidence,"source":f.source,"changed_at":f.changed_at})));
        edges.push(edge(id,"occurred_in",case_id,"Registry field recorded for this episode"));
    }
    for l in &c.learnings {
        let id=Uuid::new_v4();
        let own=l.items.iter().find(|i|i.slot=="own_words").map(|i|i.text.as_str()).unwrap_or("Surgeon reflection");
        nodes.push(node(id,"reflection","case_specific",own.to_string(),"reported",
            format!("Learning ordinal {}; shown_by={}; added_after_seal={}",l.ordinal,l.shown_by,l.added_after_seal),
            "durable",serde_json::json!({"ordinal":l.ordinal,"sign_tags":l.sign_tags,"how_showed":l.how_showed,
                "items":l.items.iter().map(|x|serde_json::json!({"slot":x.slot,"text":x.text,"origin":x.origin})).collect::<Vec<_>>(),
                "amendments":l.amendments.iter().map(|x|serde_json::json!({"slot":x.slot,"text":x.text,"created_at":x.created_at})).collect::<Vec<_>>(),
                "added_after_seal":l.added_after_seal})));
        edges.push(edge(id,"derived_from",case_id,"Surgeon-entered reflection attached to case"));
    }
    if !c.tags.is_empty() {
        let id=Uuid::new_v4();
        nodes.push(node(id,"context_factor","case_specific","Registry case tags".into(),"reported",
            "Registry tags kept verbatim".into(),"episodic",serde_json::json!({"tags":c.tags})));
        edges.push(edge(id,"occurred_in",case_id,"Tags attached to registry case"));
    }
    Ok((nodes,edges))
}

#[cfg(test)]
mod tests {
    use super::*;
    fn fixture()->RegistryCase {
        RegistryCase { source_case_ref:"sr-fixture".into(),procedure_module:"cholecystectomy".into(),
            procedure_label:Some("Laparoscopic cholecystectomy".into()),surgery_date:Some("2026-10-01".into()),
            status:"captured".into(),
            values:vec![
                RegistryFieldValue{field:"approach".into(),value:serde_json::json!("Laparoscopic"),source:Some("chip".into()),evidence:None,changed_at:None},
                RegistryFieldValue{field:"derived_score".into(),value:serde_json::json!(4),source:Some("derived".into()),evidence:None,changed_at:None}],
            learning_answer:Some("yes".into()),learning_sealed_at:Some("2026-10-02T00:00:00Z".into()),
            learnings:vec![RegistryLearning{ordinal:1,shown_by:"nothing".into(),sign_tags:vec!["difficult anatomy".into()],
                how_showed:Some("odd".into()),items:vec![RegistryLearningItem{slot:"own_words".into(),text:"Synthetic reflection".into(),origin:"own_words".into()}],
                amendments:vec![],added_after_seal:false}],tags:vec![]}
    }
    #[test] fn maps_case_values_and_learning(){let (n,e)=map_registry_case(&fixture()).unwrap();assert!(n.iter().any(|x|x["node_type"]=="case_episode"));assert!(n.iter().any(|x|x["node_type"]=="reflection"));assert!(e.iter().any(|x|x["relation"]=="derived_from"));}
    #[test] fn refuses_unsaved_or_unsealed(){let mut c=fixture();c.status="planned".into();assert!(map_registry_case(&c).is_err());c.status="captured".into();c.learning_sealed_at=None;assert!(map_registry_case(&c).is_err());}
    #[test] fn derived_fields_are_not_observation_signals(){let mut c=fixture();c.values.retain(|v|v.source.as_deref()==Some("derived"));let (n,_)=map_registry_case(&c).unwrap();assert_eq!(n.len(),2);}
    #[test] fn pseudonym_changes_with_salt(){assert_ne!(pseudonymous_ref("case-1",b"a"),pseudonymous_ref("case-1",b"b"));}
}

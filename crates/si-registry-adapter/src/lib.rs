//! Offline adapter from the Surgical Registry's de-identified export contract.
//!
//! This crate deliberately has no database, network, Supabase, or credential dependency.
//! Authorization, de-identification, date shifting, and pseudonym generation are the
//! responsibility of the trusted exporter in the source registry.

use serde::{Deserialize, Serialize};
use serde_json::Value;
use std::collections::{BTreeMap, HashSet};
use uuid::Uuid;
use si_core::{PortableStateV2, Provenance, SourceArtifact};
use chrono::{DateTime, Utc};

pub const REGISTRY_EXPORT_FORMAT: &str = "surgical-registry-export";
pub const REGISTRY_EXPORT_VERSION: u32 = 1;
pub const GRAPH_FORMAT: &str = "surgical-intelligence-knowledge-graph";
pub const GRAPH_VERSION: u32 = 1;

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct RegistryExport {
    pub format: String,
    pub version: u32,
    pub exported_at: String,
    pub source: RegistrySource,
    pub cases: Vec<RegistryCase>,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct RegistrySource {
    pub system: String,
    pub schema_family: String,
    pub registry_version: Option<String>,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct RegistryCase {
    /// Keyed pseudonym generated by the trusted exporter; never a registry UUID or study ID.
    pub source_case_ref: String,
    /// Optional keyed pseudonym for the surgeon of record. Never a user UUID, email, or initials.
    pub surgeon_ref: Option<String>,
    /// The source exporter must enforce its explicit purpose/consent policy before setting this.
    pub export_authorized: bool,
    pub procedure_module: String,
    pub procedure_label: Option<String>,
    /// This date should be shifted or coarsened by the trusted exporter where required.
    pub surgery_date: Option<String>,
    pub status: String,
    pub values: Vec<RegistryFieldValue>,
    /// Full field_provenance history, oldest first. Values alone are only the current state.
    pub field_history: Vec<RegistryFieldHistory>,
    pub learning_answer: Option<String>,
    pub learning_sealed_at: Option<String>,
    pub learnings: Vec<RegistryLearning>,
    pub tags: Vec<RegistryTag>,
    #[serde(default)]
    pub media_assets: Vec<RegistryMediaAsset>,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct RegistryFieldValue {
    pub field: String,
    pub value: Value,
    pub source: Option<String>,
    pub evidence: Option<String>,
    pub changed_at: Option<String>,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct RegistryFieldHistory {
    pub field: String,
    pub value: Value,
    pub source: String,
    pub evidence: Option<String>,
    pub changed_at: String,
    /// Optional keyed pseudonym for the person who made this change.
    pub actor_ref: Option<String>,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct RegistryLearning {
    pub ordinal: u8,
    pub shown_by: String,
    pub sign_tags: Vec<String>,
    pub how_showed: Option<String>,
    pub items: Vec<RegistryLearningItem>,
    pub amendments: Vec<RegistryAmendment>,
    pub added_after_seal: bool,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct RegistryLearningItem {
    pub slot: String,
    pub text: String,
    pub origin: String,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct RegistryAmendment {
    pub slot: String,
    pub text: String,
    pub created_at: String,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct RegistryTag {
    pub name: String,
    pub category: String,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum FieldOrigin {
    Said,
    Default,
    Derived,
    Chip,
    HistopathPhoto,
    Manual,
    Unknown,
}

impl FieldOrigin {
    pub fn parse(raw: Option<&str>) -> Self {
        match raw {
            Some("said") => Self::Said,
            Some("default") => Self::Default,
            Some("derived") => Self::Derived,
            Some("histopath_photo") => Self::HistopathPhoto,
            Some("manual") => Self::Manual,
            Some("chip") => Self::Chip,
            _ => Self::Unknown,
        }
    }

    pub fn epistemic(&self) -> &'static str {
        match self {
            Self::Said | Self::Chip | Self::HistopathPhoto | Self::Manual => "reported",
            Self::Default | Self::Derived => "inferred",
            Self::Unknown => "hypothesis",
        }
    }

    /// This controls whether a field may contribute to a candidate learning signal.
    /// Defaulted, derived, and unknown-origin values remain in the graph but are not
    /// eligible to be treated as direct surgeon observations.
    pub fn is_candidate_for_learning(&self) -> bool {
        matches!(
            self,
            Self::Said | Self::Chip | Self::HistopathPhoto | Self::Manual
        )
    }
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct KnowledgeGraphEnvelope {
    pub format: String,
    pub version: u32,
    pub exported_at: String,
    pub graph: KnowledgeGraph,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct KnowledgeGraph {
    pub nodes: Vec<Value>,
    pub edges: Vec<Value>,
}

/// Stable keyed pseudonym helper for a registry-side exporter. This is
/// pseudonymization, not anonymization; keep the secret salt outside exported data.
pub fn pseudonymous_ref(source_ref: &str, salt: &[u8]) -> String {
    use hmac::{Hmac, Mac};
    use sha2::Sha256;

    let mut mac = Hmac::<Sha256>::new_from_slice(salt)
        .expect("HMAC accepts keys of any length");
    mac.update(source_ref.as_bytes());
    let bytes = mac.finalize().into_bytes();
    format!("sr-{}", hex::encode(&bytes[..16]))
}

fn stable_id(name: &str) -> Uuid {
    Uuid::new_v5(&Uuid::NAMESPACE_URL, name.as_bytes())
}

fn source_time(exported_at: &str, candidate: Option<&str>) -> String {
    candidate
        .and_then(|s| chrono::DateTime::parse_from_rfc3339(s).ok())
        .map(|dt| dt.to_rfc3339())
        .unwrap_or_else(|| exported_at.to_string())
}

#[allow(clippy::too_many_arguments)]
fn node(
    id: Uuid,
    kind: &str,
    scope: &str,
    label: String,
    epistemic: &str,
    observed_at: &str,
    note: String,
    retention: &str,
    status: &str,
    data: Value,
) -> Value {
    serde_json::json!({
        "id": id,
        "node_type": kind,
        "knowledge_scope": scope,
        "label": label,
        "epistemic_status": epistemic,
        "confidence": null,
        "lifecycle_status": status,
        "retention": retention,
        "provenance": {
            "source_type": "surgical_registry",
            "source_id": null,
            "source_version": null,
            "note": note
        },
        "temporal": {
            "observed_at": observed_at,
            "valid_from": null,
            "valid_until": null
        },
        "review": {
            "state": "not_required",
            "reviewer_ref": null,
            "reviewed_at": null,
            "rationale": null
        },
        "data": data,
        "tags": []
    })
}

fn edge(
    id: Uuid,
    from: Uuid,
    relation: &str,
    to: Uuid,
    observed_at: &str,
    note: &str,
) -> Value {
    serde_json::json!({
        "id": id,
        "from": from,
        "relation": relation,
        "to": to,
        "epistemic_status": "reported",
        "lifecycle_status": "active",
        "provenance": {
            "source_type": "surgical_registry",
            "source_id": null,
            "source_version": null,
            "note": note
        },
        "observed_at": observed_at,
        "confidence": null,
        "note": null
    })
}

fn compact(value: &Value) -> String {
    match value {
        Value::String(s) => s.clone(),
        Value::Null => "not recorded".into(),
        _ => value.to_string(),
    }
}

fn validate_export(export: &RegistryExport) -> Result<(), String> {
    if export.format != REGISTRY_EXPORT_FORMAT {
        return Err(format!("unsupported registry export format: {}", export.format));
    }
    if export.version != REGISTRY_EXPORT_VERSION {
        return Err(format!("unsupported registry export version: {}", export.version));
    }
    if export.source.system != "surgical-registry"
        || export.source.schema_family != "postgres-case-values-learning-v1"
    {
        return Err("unrecognised registry source/schema family".into());
    }
    chrono::DateTime::parse_from_rfc3339(&export.exported_at)
        .map_err(|e| format!("invalid exported_at timestamp: {e}"))?;

    let mut case_refs = HashSet::new();
    for case in &export.cases {
        if case.source_case_ref.trim().is_empty() || !case_refs.insert(&case.source_case_ref) {
            return Err("case pseudonyms must be non-empty and unique in one export".into());
        }
        if !case.export_authorized {
            return Err(format!(
                "case {} is not authorized for this export purpose",
                case.source_case_ref
            ));
        }
        if !matches!(
            case.status.as_str(),
            "captured" | "pending_review" | "complete"
        ) {
            return Err(format!(
                "case {} is not in an exportable saved state",
                case.source_case_ref
            ));
        }
        if case.learning_sealed_at.is_none() {
            return Err(format!(
                "case {} has no learning seal; refusing incomplete export",
                case.source_case_ref
            ));
        }
        let mut fields = HashSet::new();
        for value in &case.values {
            if value.field.trim().is_empty() || !fields.insert(&value.field) {
                return Err(format!(
                    "case {} has empty or duplicate current field names",
                    case.source_case_ref
                ));
            }
        }
        let mut asset_refs = HashSet::new();
        for asset in &case.media_assets {
            validate_media_asset(asset, &case.source_case_ref)?;
            if !asset_refs.insert(&asset.asset_ref) {
                return Err(format!("case {} has duplicate media asset refs", case.source_case_ref));
            }
        }
        for asset in &case.media_assets {
            if let Some(parent) = &asset.parent_asset_ref {
                if parent == &asset.asset_ref || !asset_refs.contains(parent) {
                    return Err(format!("media asset {} has invalid parent asset reference", asset.asset_ref));
                }
            }
        }
        for learning in &case.learnings {
            if !(1..=3).contains(&learning.ordinal) {
                return Err(format!("case {} has an invalid learning ordinal", case.source_case_ref));
            }
            if !matches!(learning.shown_by.as_str(), "photo" | "clip" | "nothing") {
                return Err(format!("case {} has an invalid learning media type", case.source_case_ref));
            }
            for item in &learning.items {
                if !matches!(item.origin.as_str(), "own_words" | "box" | "asked") {
                    return Err(format!("case {} has an unknown learning item origin", case.source_case_ref));
                }
            }
        }
    }
    Ok(())
}


fn validate_media_asset(asset: &RegistryMediaAsset, case_ref: &str) -> Result<(), String> {
    if !asset.export_authorized { return Err(format!("media asset {} for case {} is not authorized", asset.asset_ref, case_ref)); }
    if asset.asset_ref.trim().is_empty() || asset.storage_ref.trim().is_empty() {
        return Err("media asset reference and storage_ref must be non-empty".into());
    }
    let path = std::path::Path::new(&asset.storage_ref);
    if asset.storage_ref.contains('\\') || asset.storage_ref.contains(':') || path.is_absolute()
        || path.components().any(|c| matches!(c, std::path::Component::ParentDir | std::path::Component::RootDir | std::path::Component::Prefix(_))) {
        return Err(format!("media asset {} storage_ref must be a safe relative path", asset.asset_ref));
    }
    if asset.storage_ref.contains('?') || asset.storage_ref.contains('#') || asset.storage_ref.contains("://") {
        return Err(format!("media asset {} storage_ref must not contain URL credentials/query data", asset.asset_ref));
    }
    if !matches!(asset.modality.as_str(), "image"|"video"|"audio"|"document"|"frame"|"clip") {
        return Err(format!("media asset {} has unsupported modality", asset.asset_ref));
    }
    if asset.sha256.len()!=64 || !asset.sha256.bytes().all(|b| b.is_ascii_hexdigit()) {
        return Err(format!("media asset {} has invalid SHA-256", asset.asset_ref));
    }
    if let (Some(a),Some(b)) = (asset.frame_start_ms, asset.frame_end_ms) {
        if b<a { return Err(format!("media asset {} has invalid frame interval", asset.asset_ref)); }
    }
    if let Some(n) = asset.learning_ordinal { if !(1..=3).contains(&n) { return Err(format!("media asset {} has invalid learning ordinal", asset.asset_ref)); } }
    if let Some(t) = &asset.captured_at { DateTime::parse_from_rfc3339(t).map_err(|e| format!("media asset {} invalid captured_at: {e}", asset.asset_ref))?; }
    Ok(())
}

/// Convert approved media metadata to v2 source-artifact records. No bytes or secrets are copied.
pub fn map_registry_media_assets(export: &RegistryExport, state: &mut PortableStateV2) -> Result<(), String> {
    validate_export(export)?;
    for case in &export.cases {
        let episode_id = Uuid::new_v5(&Uuid::NAMESPACE_URL, format!("surgical-registry:{}:episode", case.source_case_ref).as_bytes());
        for asset in &case.media_assets {
            validate_media_asset(asset, &case.source_case_ref)?;
            let id = Uuid::new_v5(&Uuid::NAMESPACE_URL, format!("surgical-registry:{}:media:{}", case.source_case_ref, asset.asset_ref).as_bytes());
            let parent_artifact_id = asset.parent_asset_ref.as_ref().map(|parent| {
                Uuid::new_v5(&Uuid::NAMESPACE_URL, format!("surgical-registry:{}:media:{}", case.source_case_ref, parent).as_bytes())
            });
            let source_node_id = if let Some(ordinal) = asset.learning_ordinal {
                if !case.learnings.iter().any(|learning| learning.ordinal == ordinal) {
                    return Err(format!("media asset {} references missing learning ordinal {}", asset.asset_ref, ordinal));
                }
                Uuid::new_v5(&Uuid::NAMESPACE_URL, format!("surgical-registry:{}:learning:{}:reflection", case.source_case_ref, ordinal).as_bytes())
            } else { episode_id };
            let observed_at = asset.captured_at.as_deref().unwrap_or(&export.exported_at);
            let imported_at = DateTime::parse_from_rfc3339(&export.exported_at).map_err(|e| format!("invalid export timestamp: {e}"))?.with_timezone(&Utc);
            let mut metadata = asset.metadata.clone();
            metadata.insert("source_case_ref".into(), Value::String(case.source_case_ref.clone()));
            if let Some(ordinal) = asset.learning_ordinal { metadata.insert("learning_ordinal".into(), Value::from(ordinal)); }
            metadata.insert("captured_at".into(), Value::String(observed_at.into()));
            state.source_artifacts.push(SourceArtifact {
                id,
                modality: asset.modality.clone(),
                media_type: asset.media_type.clone(),
                mime_type: asset.mime_type.clone(),
                sha256: Some(asset.sha256.to_ascii_lowercase()),
                byte_length: Some(asset.byte_length),
                availability: "available".into(),
                storage_ref: Some(asset.storage_ref.clone()),
                source_node_id: Some(source_node_id),
                parent_artifact_id,
                frame_start_ms: asset.frame_start_ms,
                frame_end_ms: asset.frame_end_ms,
                imported_at,
                provenance: Provenance {
                    source_type: "surgical_registry_media".into(),
                    source_id: Some(asset.asset_ref.clone()),
                    source_version: Some("registry-media-export-v1".into()),
                    note: Some(format!("Approved media from pseudonymous case {}", case.source_case_ref)),
                },
                metadata,
            });
        }
    }
    state.validate()
}

/// Convert one already-authorized registry export to a portable graph envelope.
/// Node and edge IDs are deterministic so re-importing the same source episode does
/// not create duplicate graph objects. This mapper does not merge revisions into a
/// persisted graph; the graph store must still apply lifecycle/update policies.
pub fn map_registry_export(
    export: &RegistryExport,
) -> Result<KnowledgeGraphEnvelope, String> {
    validate_export(export)?;
    let mut nodes = Vec::new();
    let mut edges = Vec::new();

    for case in &export.cases {
        let (mut case_nodes, mut case_edges) = map_registry_case(case, &export.exported_at)?;
        nodes.append(&mut case_nodes);
        edges.append(&mut case_edges);
    }

    Ok(KnowledgeGraphEnvelope {
        format: GRAPH_FORMAT.into(),
        version: GRAPH_VERSION,
        exported_at: export.exported_at.clone(),
        graph: KnowledgeGraph { nodes, edges },
    })
}

/// Map one saved and sealed case. Exposed separately for deterministic unit tests.
pub fn map_registry_case(
    case: &RegistryCase,
    exported_at: &str,
) -> Result<(Vec<Value>, Vec<Value>), String> {
    if case.source_case_ref.trim().is_empty() {
        return Err("source_case_ref must be a non-empty pseudonymous reference".into());
    }
    if !case.export_authorized {
        return Err("case is not authorized for export".into());
    }
    if !matches!(case.status.as_str(), "captured" | "pending_review" | "complete") {
        return Err("only saved cases may be exported".into());
    }
    let sealed_at = case
        .learning_sealed_at
        .as_deref()
        .ok_or_else(|| "case learning must be sealed before knowledge export".to_string())?;
    let sealed_at = source_time(exported_at, Some(sealed_at));
    let prefix = format!("surgical-registry:{}", case.source_case_ref);
    let case_id = stable_id(&format!("{prefix}:episode"));
    let case_observed_at = case
        .surgery_date
        .as_deref()
        .and_then(|d| chrono::NaiveDate::parse_from_str(d, "%Y-%m-%d").ok())
        .and_then(|d| d.and_hms_opt(0, 0, 0))
        .map(|d| chrono::DateTime::<chrono::Utc>::from_naive_utc_and_offset(d, chrono::Utc).to_rfc3339())
        .unwrap_or_else(|| exported_at.to_string());

    let mut nodes = vec![node(
        case_id,
        "case_episode",
        "case_specific",
        format!(
            "{} — {}",
            case.procedure_label
                .as_deref()
                .unwrap_or(&case.procedure_module),
            case.surgery_date.as_deref().unwrap_or("date not recorded")
        ),
        "reported",
        &case_observed_at,
        format!("Pseudonymous source ref {}; status {}", case.source_case_ref, case.status),
        "episodic",
        "active",
        serde_json::json!({
            "procedure_module": case.procedure_module,
            "procedure_label": case.procedure_label,
            "surgery_date": case.surgery_date,
            "surgeon_ref": case.surgeon_ref,
            "learning_answer": case.learning_answer,
            "learning_sealed_at": sealed_at
        }),
    )];
    let mut edges = Vec::new();

    // Keep all current structured values. Directly reported/tapped values are
    // candidate learning signals; defaults/derived/unknown values remain visible
    // but are explicitly marked ineligible for independent learning.
    for field in &case.values {
        let origin = FieldOrigin::parse(field.source.as_deref());
        let field_id = stable_id(&format!("{prefix}:field:{}:current", field.field));
        let observed_at = source_time(exported_at, field.changed_at.as_deref());
        let kind = outcome_field(&field.field);
        nodes.push(node(
            field_id,
            kind,
            "case_specific",
            format!("{}: {}", field.field, compact(&field.value)),
            origin.epistemic(),
            &observed_at,
            format!("Current case_values field {}; source {:?}", field.field, field.source),
            "episodic",
            "active",
            serde_json::json!({
                "field": field.field,
                "value": field.value,
                "source": field.source,
                "evidence": field.evidence,
                "changed_at": field.changed_at,
                "learning_signal_eligible": origin.is_candidate_for_learning()
            }),
        ));
        edges.push(edge(
            stable_id(&format!("{prefix}:edge:{}:current:occurred_in", field.field)),
            field_id,
            "occurred_in",
            case_id,
            &observed_at,
            "Current structured value recorded for this episode",
        ));
    }

    // Full field_provenance rows are retained as time-ordered observations.
    // Earlier revisions are superseded, never silently discarded.
    let mut history_by_field: BTreeMap<&str, Vec<&RegistryFieldHistory>> = BTreeMap::new();
    for history in &case.field_history {
        history_by_field.entry(&history.field).or_default().push(history);
    }
    for (field_name, mut history) in history_by_field {
        history.sort_by(|a, b| a.changed_at.cmp(&b.changed_at));
        for (index, item) in history.iter().enumerate() {
            let observed_at = source_time(exported_at, Some(&item.changed_at));
            let history_id = stable_id(&format!(
                "{prefix}:field-history:{field_name}:{}:{index}",
                item.changed_at
            ));
            let latest = index + 1 == history.len();
            nodes.push(node(
                history_id,
                outcome_field(field_name),
                "case_specific",
                format!("{} history: {}", field_name, compact(&item.value)),
                FieldOrigin::parse(Some(&item.source)).epistemic(),
                &observed_at,
                format!("field_provenance history for {}; actor pseudonym {:?}", field_name, item.actor_ref),
                "episodic",
                if latest { "active" } else { "superseded" },
                serde_json::json!({
                    "field": field_name,
                    "value": item.value,
                    "source": item.source,
                    "evidence": item.evidence,
                    "actor_ref": item.actor_ref,
                    "changed_at": item.changed_at,
                    "learning_signal_eligible": FieldOrigin::parse(Some(&item.source)).is_candidate_for_learning()
                }),
            ));
            edges.push(edge(
                stable_id(&format!("{prefix}:edge:{field_name}:history:{index}:occurred_in")),
                history_id,
                "occurred_in",
                case_id,
                &observed_at,
                "Append-only field_provenance change",
            ));
        }
    }

    // Each My Experience learning is retained as a parent reflection. The exact
    // labelled slots, their origin, sign tags, and post-seal amendments are kept.
    for learning in &case.learnings {
        let learning_key = format!("{prefix}:learning:{}", learning.ordinal);
        let learning_id = stable_id(&format!("{learning_key}:reflection"));
        let own_words = learning
            .items
            .iter()
            .find(|item| item.slot == "own_words")
            .map(|item| item.text.as_str())
            .unwrap_or("Surgeon reflection");
        let amended_at = learning
            .amendments
            .last()
            .map(|amendment| amendment.created_at.as_str());
        let observed_at = source_time(exported_at, amended_at.or(Some(&sealed_at)));
        nodes.push(node(
            learning_id,
            "reflection",
            "case_specific",
            own_words.to_string(),
            "reported",
            &observed_at,
            format!(
                "My Experience learning ordinal {}; added_after_seal={}",
                learning.ordinal, learning.added_after_seal
            ),
            "durable",
            "active",
            serde_json::json!({
                "ordinal": learning.ordinal,
                "shown_by": learning.shown_by,
                "sign_tags": learning.sign_tags,
                "how_showed": learning.how_showed,
                "items": learning.items.iter().map(|item| serde_json::json!({
                    "slot": item.slot,
                    "text": item.text,
                    "origin": item.origin
                })).collect::<Vec<_>>(),
                "amendments": learning.amendments.iter().map(|amendment| serde_json::json!({
                    "slot": amendment.slot,
                    "text": amendment.text,
                    "created_at": amendment.created_at
                })).collect::<Vec<_>>(),
                "added_after_seal": learning.added_after_seal
            }),
        ));
        edges.push(edge(
            stable_id(&format!("{learning_key}:edge:derived_from_episode")),
            learning_id,
            "derived_from",
            case_id,
            &observed_at,
            "Surgeon-entered learning attached to the episode",
        ));

        // Semantic slots that explicitly describe an observation or an action
        // get typed child nodes. We do not infer a selected decision from the
        // registry's "other options" free-text box.
        for item in &learning.items {
            let (kind, relation) = match item.slot.as_str() {
                "saw" | "first_told" => ("observation", "observed_during"),
                "did" => ("action", "performed_during"),
                _ => continue,
            };
            if item.text.trim().is_empty() {
                continue;
            }
            let item_id = stable_id(&format!("{learning_key}:slot:{}", item.slot));
            nodes.push(node(
                item_id,
                kind,
                "case_specific",
                format!("{}: {}", item.slot, item.text),
                "reported",
                &observed_at,
                format!("My Experience slot {}; origin={}", item.slot, item.origin),
                "episodic",
                "active",
                serde_json::json!({
                    "slot": item.slot,
                    "text": item.text,
                    "origin": item.origin,
                    "learning_ordinal": learning.ordinal
                }),
            ));
            edges.push(edge(
                stable_id(&format!("{learning_key}:edge:{}:{}", item.slot, relation)),
                item_id,
                relation,
                case_id,
                &observed_at,
                "Explicit surgeon-entered My Experience slot",
            ));
        }
    }

    for tag in &case.tags {
        let tag_id = stable_id(&format!("{prefix}:tag:{}:{}", tag.category, tag.name));
        nodes.push(node(
            tag_id,
            "context_factor",
            "case_specific",
            tag.name.clone(),
            "reported",
            &case_observed_at,
            format!("Registry tag category {}", tag.category),
            "episodic",
            "active",
            serde_json::json!({"name": tag.name, "category": tag.category}),
        ));
        edges.push(edge(
            stable_id(&format!("{prefix}:tag-edge:{}:{}", tag.category, tag.name)),
            tag_id,
            "occurred_in",
            case_id,
            &case_observed_at,
            "Tag attached to registry case",
        ));
    }

    Ok((nodes, edges))
}

/// Registry field names for which the data dictionary explicitly describes an
/// outcome. Everything else remains a neutral observation until a reviewed map
/// is added; this is deliberately not inferred from arbitrary field text.
fn outcome_field(field: &str) -> &'static str {
    match field {
        "clavien_dindo_max" | "clavien_dindo_max_90d" | "readmission" | "readmission_90d"
        | "death" | "death_30d" | "death_90d" | "los_days" | "discharge_destination"
        | "reintervention" | "return_to_theatre" => "outcome",
        _ => "observation",
    }
}

